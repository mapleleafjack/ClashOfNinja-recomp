// The cell and sheet geometry the bundled IPL font replacements use.
constexpr int kCell = 24;
constexpr int kColumns = 21;
constexpr int kSheet = 512;
constexpr uint16_t kFirst = 0x20, kLast = 0xFF;
constexpr int kCellPx = kSheet * kSheet;  // pixels
constexpr int kTileBytes = kCellPx / 4;   // 2 bits a pixel

// The advance of each character, in pixels of the cell.
uint8_t advance(uint16_t c) {
    switch (c) {
    case ' ': return 5;
    case 'i': case 'l': case 'I': case 'j': case '!': case '.': case ',': case ':':
    case ';': case '\'': case '|': case '1': return 6;
    case 'M': case 'W': case 'm': case 'w': case '@': return 13;
    default: return 9;
    }
}

// An 8-bit grey image of the sheet, from the glyphs above: each character's cell, its
// bitmap drawn 8 pixels wide and 16 tall -- exactly twice the source, so the strokes stay
// even -- with its bottom sitting on the cell's baseline.
std::vector<uint8_t> sheet_image() {
    std::vector<uint8_t> px((size_t)kCellPx, 0);
    for (uint16_t c = kFirst; c <= kLast; c++) {
        if (c >= 0x7F) continue;
        const int idx = c - kFirst;
        const int cx = (idx % kColumns) * kCell, cy = (idx / kColumns) * kCell;
        const uint8_t* g = kGlyphs[c - 0x20];
        for (int dy = 0; dy < 16; dy++) {
            const uint8_t row = g[dy / 2];
            const int y = cy + kCell - 16 + dy;
            // These bitmaps put the leftmost pixel in the low bit, as the VGA sets they
            // come from do.
            for (int dx = 0; dx < 8; dx++)
                if (row & (1u << dx)) px[(size_t)y * kSheet + cx + 8 + dx] = 0xFF;
        }
    }
    return px;
}

// Linear 8-bit grey to the sheet's 2-bit, 8x8-blocked layout, as gc-font-tool writes it:
// two bytes a row inside each block, blocks across then down.
std::vector<uint8_t> tile_2bpp(const std::vector<uint8_t>& px) {
    std::vector<uint8_t> out((size_t)kTileBytes, 0);
    const int blocks = kSheet / 8;
    for (int by = 0; by < blocks; by++)
        for (int bx = 0; bx < blocks; bx++)
            for (int row = 0; row < 8; row++) {
                const uint8_t* src = &px[(size_t)(by * 8 + row) * kSheet + bx * 8];
                uint8_t* dst = &out[((size_t)by * blocks + bx) * 16 + row * 2];
                dst[0] = (src[0] & 0xC0) | (src[1] >> 2 & 0x30) | (src[2] >> 4 & 0x0C) | (src[3] >> 6);
                dst[1] = (src[4] & 0xC0) | (src[5] >> 2 & 0x30) | (src[6] >> 4 & 0x0C) | (src[7] >> 6);
            }
    return out;
}

// The font as the SDK reads it once decompressed: its header, the width of each character,
// then the sheet. Offsets as gc-font-tool's generate_fnt writes them.
std::vector<uint8_t> font_payload() {
    const std::vector<uint8_t> sheet = tile_2bpp(sheet_image());
    const int nchars = kLast - kFirst + 1;
    std::vector<uint8_t> f;

    auto be16 = [&](uint16_t v) { f.push_back((uint8_t)(v >> 8)); f.push_back((uint8_t)v); };
    auto be32 = [&](uint32_t v) {
        f.push_back((uint8_t)(v >> 24)); f.push_back((uint8_t)(v >> 16));
        f.push_back((uint8_t)(v >> 8)); f.push_back((uint8_t)v);
    };
    be16(0);                             // type: Windows-1252
    be16(kFirst);                        // first character
    be16(kLast);                         // last character
    be16(' ');                           // invalid character
    be16(kCell);                         // ascent
    be16(0);                             // descent
    be16(kCell);                         // widest character
    be16(kCell * 7 / 6);                 // leading space
    be16(kCell);                         // cell width
    be16(kCell);                         // cell height
    be32(kSheet * kSheet / 2);           // texture size
    be16(0);                             // texture format
    be16(kColumns);                      // columns of cells
    be16(kColumns);                      // rows of cells
    be16(kSheet);                        // texture width
    be16(kSheet);                        // texture height
    be16(0x30);                          // where the widths start
    be32(0x30 + nchars);                 // where the sheet starts
    be32(2 * (uint32_t)sheet.size());    // sheet size, in the units the SDK counts it
    be32(0x0055AAFFu);                   // the four shades the SDK maps 0-3 to
    for (uint16_t c = kFirst; c <= kLast; c++) f.push_back(advance(c));
    f.insert(f.end(), sheet.begin(), sheet.end());
    return f;
}

// Yay0: a mask table saying literal or link, then the literals and the links. A link is a
// 12-bit distance and a 4-bit count; count 0 takes the count from the literal stream
// instead, 18 larger, which is how longer runs are written.
std::vector<uint8_t> yay0(const std::vector<uint8_t>& in) {
    std::vector<uint8_t> masks, links, literals;
    uint8_t mask = 0;
    int bits = 0;
    auto push_bit = [&](bool literal) {
        mask = (uint8_t)((mask << 1) | (literal ? 1 : 0));
        if (++bits == 8) { masks.push_back(mask); mask = 0; bits = 0; }
    };

    // Three-byte hashing with a chain per bucket: 32 candidates is plenty for a font.
    const size_t n = in.size();
    std::vector<int> head(1 << 16, -1), prev(n, -1);
    auto hash_at = [&](size_t i) {
        return (uint32_t)((in[i] << 16 | in[i + 1] << 8 | in[i + 2]) * 2654435761u >> 16);
    };
    auto insert = [&](size_t i) {
        if (i + 2 >= n) return;
        const uint32_t h = hash_at(i);
        prev[i] = head[h];
        head[h] = (int)i;
    };

    size_t i = 0;
    while (i < n) {
        size_t best_len = 0, best_dist = 0;
        if (i + 2 < n) {
            int cand = head[hash_at(i)];
            for (int chain = 0; cand >= 0 && chain < 32; chain++) {
                const size_t dist = i - (size_t)cand;
                if (dist == 0 || dist > 4096) break;
                const size_t max_len = std::min<size_t>(273, n - i);
                size_t len = 0;
                while (len < max_len && in[(size_t)cand + len] == in[i + len]) len++;
                if (len > best_len) {
                    best_len = len;
                    best_dist = dist;
                    if (len == max_len) break;
                }
                cand = prev[cand];
            }
        }
        if (best_len >= 3) {
            push_bit(false);
            uint16_t link = (uint16_t)(best_dist - 1);
            if (best_len <= 17) {
                link |= (uint16_t)((best_len - 2) << 12);
            } else {
                literals.push_back((uint8_t)(best_len - 18));
            }
            links.push_back((uint8_t)(link >> 8));
            links.push_back((uint8_t)link);
            for (size_t k = 0; k < best_len; k++) insert(i + k);
            i += best_len;
        } else {
            push_bit(true);
            literals.push_back(in[i]);
            insert(i);
            i++;
        }
    }
    if (bits) masks.push_back((uint8_t)(mask << (8 - bits)));

    std::vector<uint8_t> out{'Y', 'a', 'y', '0'};
    auto be32 = [&](uint32_t v) {
        out.push_back((uint8_t)(v >> 24)); out.push_back((uint8_t)(v >> 16));
        out.push_back((uint8_t)(v >> 8)); out.push_back((uint8_t)v);
    };
    be32((uint32_t)n);
    be32((uint32_t)(0x10 + masks.size()));
    be32((uint32_t)(0x10 + masks.size() + links.size()));
    out.insert(out.end(), masks.begin(), masks.end());
    out.insert(out.end(), links.begin(), links.end());
    out.insert(out.end(), literals.begin(), literals.end());
    return out;
}

